package hr.avrbanac.docsis.lib;

/**
 * Helper pojo wrapper class for ground-truth tests built with {@link EchoChannelGenerator}: physical echo parameters together with the
 * results they must produce.
 */
public class TestEcho {
    private final double delay;
    private final double levelDb;
    private final double phase;
    private final String expectedSeverity;

    public TestEcho(
            final double delay,
            final double levelDb,
            final double phase,
            final String expectedSeverity) {

        this.delay = delay;
        this.levelDb = levelDb;
        this.phase = phase;
        this.expectedSeverity = expectedSeverity;
    }

    /**
     * Returns stored echo delay in symbol periods (T).
     * @return double echo delay
     */
    public double getDelay() {
        return delay;
    }

    /**
     * Returns stored echo level relative to the main signal in dB.
     * @return double echo level
     */
    public double getLevelDb() {
        return levelDb;
    }

    /**
     * Returns stored echo phase in radians.
     * @return double echo phase
     */
    public double getPhase() {
        return phase;
    }

    /**
     * Returns stored expected micro-reflection severity name (CableLabs thresholds).
     * @return {@link String} severity name
     */
    public String getExpectedSeverity() {
        return expectedSeverity;
    }

    /**
     * Creates pre-eq string for this echo.
     * @return {@link String} pre-eq string generated by {@link EchoChannelGenerator}
     */
    public String toPreEqString() {
        return EchoChannelGenerator.singleEcho(delay, levelDb, phase);
    }

    @Override
    public String toString() {
        return "echo{delay=" + delay + "T, level=" + levelDb + "dB, phase=" + phase + "}";
    }
}
